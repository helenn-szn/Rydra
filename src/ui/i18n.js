const LANGS = [
  { id: 'en', name: 'English' },
  { id: 'pcm', name: 'Naijá (Pidgin)' },
  { id: 'fr', name: 'Français' },
  { id: 'es', name: 'Español' },
];
const DICTS = { en, pcm, fr, es };

let lang = 'en';

function detectLang(navLang) {
  const l = String(navLang || 'en').toLowerCase();
  if (l.startsWith('fr')) return 'fr';
  if (l.startsWith('es')) return 'es';
  return 'en';
}

function setLang(id) { lang = DICTS[id] ? id : 'en'; }
function getLang() { return lang; }

function t(key, vars) {
  let s = (DICTS[lang] && DICTS[lang][key]) || en[key] || key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? vars[k] : `{${k}}`));
  return s;
}

module.exports = { t, setLang, getLang, detectLang, LANGS, DICTS };
